#!/usr/bin/env python3
"""soobak 1-shot 게이트 — PreToolUse(Edit|Write) 리마인더.

dev/unity 글의 prose Edit/Write마다 '제출 전 한 번에 끝내기' 게이트를 항상 주입한다.
같은 문단을 여러 턴 반복 수정하게 만든 실패(비문·연어 충돌·정의 부정확·반응적 단일축
패치)를 끊기 위한 강제 가시화 장치. (비차단)

코드/SVG/표 편집(종결어미 없음)에는 끼어들지 않는다.
"""
import sys, json, re

try:
    data = json.load(sys.stdin)
except Exception:
    sys.exit(0)

ti = data.get("tool_input", {}) or {}
path = ti.get("file_path", "") or ""
if "dev/unity" not in path or not path.endswith(".md"):
    sys.exit(0)

text = ti.get("new_string") or ti.get("content") or ""
if not re.search(r"[다요][.!?]", text):  # 산문 문장이 있을 때만
    sys.exit(0)

checklist = (
    "⚠️ soobak 1-shot 게이트 — 이 편집을 *최종*으로 만들 것 (사용자가 결함을 짚으면 = 이 게이트 실패):\n"
    "0. ⛔ 구조 먼저(아래 문장 게이트보다 상위): 요청이 '전면 재수정·재구성·구조·논리 골격·흐름'이거나 같은 섹션을 2회+ 손대는 중이면 — 문장 Edit STOP. 먼저 단락 골격(각 1줄 명제)+스파인 진단(이질 주제 접합·전방참조·제목/H2역할 불일치)을 *표로 출력*하라. **1~5는 문장 단위라 구조를 못 본다 — denylist 0·5축 통과가 스파인 정합을 보장하지 않는다.**\n"
    "0b. ⛔ 섹션 완결성(거짓 보고 방지): '섹션 전면 재수정/재설계' 요청이면 *도입 문단만 다듬는 것은 실패*다. 먼저 **missing-beat audit**를 표로 출력 — 완결된 설명이 가질 beat(원리·정의·기본값/오버로드 동치·**worked 수치 예**·**실전 use-case 권장**·일반화·내부 메커니즘) 나열 → 각 '있음/없음' → **없음을 채워라**. 사용자가 붙여넣은 문단=시작점이지 작업 범위가 아니다. '전면 재수정' 보고는 *추가한 beat 목록* + 바꾼 문단 수/총 문단 수 증거 없이는 금지(2026-06-24 도입1문단↔11-beat 거짓보고 재발 차단).\n"
    "1. 새 문장을 *처음 보는 독자처럼* 소리내어 읽기 — 멈칫 1회라도면 재작성.\n"
    "2. 비문: 각 문장에 완결된 주절이 있는가? `~는지가/~기/~음`이 실제 서술어에 걸리는가? `~때문입니다`가 받칠 절이 있는가?\n"
    "3. ⛔ 신규 동사–목적어 연어 (이 세션 ~6회 user-reject 의 단일 최대 원인 — 독립 리뷰어도 이 클래스는 못 잡음, LLM 공통 맹점): *이번에 새로 쓴* 동사를 목적어와 짝지어 한 줄씩 적고, 각 쌍이 '원어민이 이 목적어에 쓰는 *가장 평이·표준* 동사인가, 아니면 생생함·병렬 맞추려 집은 synonym 인가' 판정 → 후자면 literal 로. 실패 표본: 능력을 '여는'(→허용하는)·사본을 '벌'로 '올라가다'(→두 배로 차지)·화질을 '맞바꾸다'(→사이에서 정하다)·어긋남을 '메우다'(→바로잡다). **clean 한 원본 문장은 재설계가 내용·위치를 안 바꾸면 re-verb 금지**(멀쩡한 표현을 망치지 말 것). 프레이밍(bridge·thesis·reveal) 문장은 *가중* 점검. (참고 비롯되다=부정 근원→`이점`과 충돌 / 좌우하다=거창 / 가지다=has 직역 / 띄우다=구어)\n"
    "4. 게이트 일괄: 행위자·논리 · register denylist · Given→New·용어 첫 등장 풀이 · 글 전체와 사실/정의 정합(genus 충돌 등).\n"
    "5. 같은 문단을 2회+ 손대는 중이면 패치 중단 → 전체 재작성.\n"
    "6. ⛔ 전축 스윕 + gold-standard 대조(RC1·RC3·RC5 — 이 클래스가 한 문단 ~8라운드 반려의 근본): 제출 전 ONE 패스로 *모든 축을 함께* 점검하라(register·번역투·**리듬/동사 분포**·구조·연어·사실). 단일 축만 고치고 done 선언 금지(반응적 whack-a-mole). 그리고 **반드시 동일 글/시리즈의 *받아들여진* gold-standard 형제 문단(가능하면 같은 주제)을 하나 지목해 문장 길이·복문 흐름(staccato 금지)·동사 분포를 나란히 대조**하라 — 회피리스트(denylist)만으로는 naturalness를 못 본다. 격식 통과 ≠ 자연스러움.\n"
    "7. ⛔ 도입 문단 *또는 API/도구를 처음 소개하는 문장*이면(위치 불문 — 2026-07-03 이상본 미달 2회 지점): ①첫 문장이 직전 절의 *현상/필요*를 잇는가 — API/용어 명명은 필요·전략 평서 뒤 '이때 사용하는 X가 ~입니다'로 2문장째(thesis-first ≠ API-first. 'X 인터페이스로 우회할 수 있습니다' 같은 API-first 개시 금지. '도입 문단 전용'으로 좁혀 읽지 말 것 — 좁은 스코핑이 재발 근본) ②분기/하위 문단이 쓸 용어쌍을 도입이 그대로 심는가(도입에만 나오는 고아 용어 금지) ③정적 제약('~할 수 없다')이 아니라 시스템 행동('Unity는 한쪽을 유지하고 다른 쪽을 다시 계산')으로 닫는가. 앞 절과의 중복은 삭제 말고 *각도 전환* 재진술('값의 의미'→'해석하는 기준') — 삭제 후 논리 갭이 생기면 오처방.\n"
    "8. ⛔ 외부 처방 verbatim 금지: 리뷰어 제안·훅 예시 어휘는 결함 *탐지*로만 취하고, 수리 문안은 corpus·gold-standard·사용자 이상본에서 재유도하라(실측: 리뷰어 처방 3건 중 2건이 이상본 역방향). 규칙 적용(삭제·치환) 직후 그 자리를 재독해 연쇄 결함(문장 과적·고리 소실)을 점검. content-carrying 도식 도입('아래 예시는 X 상황입니다')은 빈 연결문이 아니다 — 지우지 말 것.\n"
    "9. ⛔ 양성 특질 대조(2026-07-03 이상본 #3 — 결함 0 ≠ 이상본. 리뷰어 2회 PASS 문단이 이상본으로 교체된 근본): ①두 시스템의 판정이 갈리는 현상(컴파일러 OK/직렬화 NO 류)은 *두 시스템을 각 문장의 주체로 명명* — 무주체 은유('걸러지지 않는다') 금지 ②결과 절마다 원인 재진술(~이므로 반복 허용 — 간결 규칙을 load-bearing 인과 고리에 적용 금지) ③구성요소 정밀 명사(키와 값·List<TKey>) 유지, '데이터/내용' 강등 금지 ④변환·복원 메커니즘의 핵심 부사('순서대로') 보존 ⑤행위자+기지 개념 비유 접지('Unity는 ~를 일반 필드처럼 저장') — 무행위자 수동('~가 대신 저장됩니다') 회피 ⑥시간 표지는 독자 행위 층위('저장 직전'·'다시 불러온 뒤') 우선 ⑦'오류가 발생하다'는 표준 연어 — 회피 사전을 토큰으로 과교정해 더 나쁜 은유를 고르지 말 것.\n"
    "'좋다/자연스럽다' 선언 금지 — 통과한 점검 항목만 적고 제출."
)

flags = []
if re.search(r"비롯[되돼된될됩]", text):
    flags.append("· `비롯되다`: 부정적 근원 뉘앙스 — `이점` 등 긍정 결과 주어와 충돌 확인")
if re.search(r"는지가\s", text):
    flags.append("· `~는지가`(간접의문 명사절+가 주어): 비문 위험 — `~방식이/~점이`로 풀 것")
if re.search(r"`[^`]+`\s*(?:인터페이스|어트리뷰트|함수|메서드|클래스)?\s*[로를]\s*(?:우회|사용|구현|해결)할 수", text):
    flags.append("· API-first 의심: 도구 명명 앞에 필요·전략 평서 문장이 있는가? 이상본 패턴='~해야 합니다. 이때 사용하는 X가 ~입니다' (item 7·9)")
if re.search(r"걸러지", text):
    flags.append("· `걸러지다`: 무주체 여과 은유 — 판정 주체(컴파일러/직렬화 등 시스템)를 문장 주어로 명명할 것 (item 9-①)")
if flags:
    checklist += "\n탐지:\n" + "\n".join(flags)

print(json.dumps({
    "hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "additionalContext": checklist,
    }
}))
sys.exit(0)
